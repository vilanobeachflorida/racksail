package main

import (
	"fmt"
	"go/format"
	"strings"
)

// smallMark is the mark redrawn on a 16-pixel grid for favicons and
// terminals. At that size the full drawing's gaps between sails, hull and
// wave fall between pixels and the shapes blur together, so this version
// puts every edge where a pixel can show it.
var smallMark = []Shape{
	{"mainsail", true, MustPath("M8.2 1C10.6 2.8 12.6 5.6 13.9 9L7.6 9C8.6 6.4 8.9 3.7 8.2 1Z")},
	{"jib", false, MustPath("M7 3.2C7.1 5.3 6.8 7.2 6.1 9L2.2 9C4.2 7.4 6 5.3 7 3.2Z")},
	{"hull", true, MustPath("M15.8 10L13.4 12.7C9.5 12 5.4 11.8 1 12.1C3.5 10.6 9.3 10 15.8 10Z")},
	{"wave", false, MustPath("M16 13.2C13.2 15.4 10.4 15.1 8 14.5C5.4 13.8 2.8 13.9 0 15C2.6 12.9 5.6 12.7 8.1 13.3C10.8 14 13.4 14.3 16 13.2Z")},
}

const smallMarkSize = 16

// grid samples shapes into pixels for terminal art: "i" for ink, "s" for
// sea and "." for empty. Each pixel goes to the shape covering most of it,
// and where two shapes would touch, the pixel they cover less is left
// empty, so the sails, hull and wave stay apart even without color. Empty
// rows at the top and bottom are dropped.
func grid(shapes []Shape, t Transform, w, h int) []string {
	const threshold = 0.4
	covs := make([][]float64, len(shapes))
	for i, s := range shapes {
		covs[i] = coverage(s.Path.Apply(t), w, h)
	}
	owner := make([]int, w*h)
	best := make([]float64, w*h)
	for p := range owner {
		owner[p] = -1
		for i := range shapes {
			if c := covs[i][p]; c >= threshold && c > best[p] {
				owner[p], best[p] = i, c
			}
		}
	}
	for y := range h {
		for x := range w {
			p := y*w + x
			for _, d := range [][2]int{{1, 0}, {0, 1}, {1, 1}, {-1, 1}} {
				nx, ny := x+d[0], y+d[1]
				if owner[p] < 0 || nx < 0 || nx >= w || ny >= h {
					continue
				}
				q := ny*w + nx
				if owner[q] < 0 || owner[q] == owner[p] {
					continue
				}
				if best[q] < best[p] {
					owner[q] = -1
				} else {
					owner[p] = -1
				}
			}
		}
	}
	rows := make([]string, 0, h)
	for y := range h {
		row := make([]byte, w)
		for x := range w {
			switch o := owner[y*w+x]; {
			case o < 0:
				row[x] = '.'
			case shapes[o].Ink:
				row[x] = 'i'
			default:
				row[x] = 's'
			}
		}
		rows = append(rows, string(row))
	}
	empty := strings.Repeat(".", w)
	for len(rows) > 0 && rows[0] == empty {
		rows = rows[1:]
	}
	for len(rows) > 0 && rows[len(rows)-1] == empty {
		rows = rows[:len(rows)-1]
	}
	return rows
}

// terminalGrids are the small and large terminal marks.
func terminalGrids() (small, large []string) {
	small = grid(smallMark, Identity, smallMarkSize, smallMarkSize)
	const largeWidth = 32
	s := largeWidth / float64(markWidth)
	large = grid(mark, Transform{Scale: s}, largeWidth, int(markHeight*s)+2)
	return small, large
}

// markGridSource is the Go file that gives internal/theme the terminal marks.
func markGridSource(small, large []string) []byte {
	var b strings.Builder
	b.WriteString("// Code generated by go run ./brand/gen; DO NOT EDIT.\n\npackage theme\n\n")
	b.WriteString("// markGrids are the mark sampled into pixels for terminals by brand/gen:\n")
	b.WriteString("// \"i\" is ink (the mainsail and hull), \"s\" sea (the jib and wave) and \".\"\n")
	b.WriteString("// empty. Two rows of pixels make one line of half-block characters.\n")
	b.WriteString("var markGrids = map[MarkSize][]string{\n")
	for _, g := range []struct {
		name string
		rows []string
	}{{"MarkSmall", small}, {"MarkLarge", large}} {
		fmt.Fprintf(&b, "%s: {\n", g.name)
		for _, r := range g.rows {
			fmt.Fprintf(&b, "%q,\n", r)
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n")
	src, err := format.Source([]byte(b.String()))
	if err != nil {
		panic(err)
	}
	return src
}

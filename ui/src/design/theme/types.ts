/**
 * The theme format, as internal/theme serializes it to JSON and
 * spec/schemas/theme.schema.json describes it.
 */
export type Color = string;

export interface Palette {
  surface: Color;
  surfaceRaised: Color;
  surfaceSunken: Color;
  text: Color;
  textMuted: Color;
  border: Color;
  borderStrong: Color;
  brand: Color;
  brandText: Color;
  accent: Color;
  accentText: Color;
  success: Color;
  successText: Color;
  warning: Color;
  warningText: Color;
  danger: Color;
  dangerText: Color;
  info: Color;
  infoText: Color;
  focus: Color;
  overlay?: Color;
  chart: Color[];
}

/** The palette tokens that hold one color each, in the order themes list them. */
export const paletteKeys = [
  "surface",
  "surfaceRaised",
  "surfaceSunken",
  "text",
  "textMuted",
  "border",
  "borderStrong",
  "brand",
  "brandText",
  "accent",
  "accentText",
  "success",
  "successText",
  "warning",
  "warningText",
  "danger",
  "dangerText",
  "info",
  "infoText",
  "focus",
  "overlay",
] as const satisfies readonly (keyof Palette)[];

export type PaletteKey = (typeof paletteKeys)[number];

export interface Font {
  family: string;
  files?: string[];
}

export interface Typography {
  sans?: Font;
  mono?: Font;
  baseSize?: string;
  scale?: number;
  weights?: { regular?: number; medium?: number; semibold?: number; bold?: number };
}

export interface Sizes {
  sm?: string;
  md?: string;
  lg?: string;
  xl?: string;
}

export type Density = "comfortable" | "compact";

export interface Tokens {
  light: Palette;
  dark: Palette;
  typography?: Typography;
  radius?: Sizes;
  density?: Density;
  shadows?: Sizes;
  motion?: { fast?: string; normal?: string; slow?: string };
  focusRing?: { width?: string; offset?: string };
}

export interface Theme {
  format: 1;
  id: string;
  name: string;
  version: string;
  license: string;
  author?: string;
  description?: string;
  tokens: Tokens;
  assets?: {
    logoLight?: string;
    logoDark?: string;
    mark?: string;
    favicon?: string;
    loginBackground?: string;
    illustrations?: Record<string, string>;
  };
  templates?: { email?: string; error?: string; maintenance?: string; suspended?: string };
  console?: {
    background?: Color;
    foreground?: Color;
    accent?: Color;
    success?: Color;
    warning?: Color;
    danger?: Color;
  };
}

/** A contrast every theme's palettes must reach. */
export interface Pair {
  foreground: string;
  background: string;
  minimum: number;
  purpose: string;
}

/** A token computed as a share of one color over another. */
export interface Derivation {
  name: string;
  from: string;
  over: string;
  share: number;
}

/** The hue ranges a status color must stay in. */
export interface Meaning {
  token: string;
  hues: [number, number][];
  name: string;
}

export interface ProtectedPalette {
  surface: Color;
  text: Color;
  border: Color;
  danger: Color;
  dangerText: Color;
  warning: Color;
  warningText: Color;
  focus: Color;
}

/** The console palette's colors, by name. */
export type ConsoleKey = keyof NonNullable<Theme["console"]>;

/** The console palette's colors in the order themes list them. */
export const consoleKeys = [
  "background",
  "foreground",
  "accent",
  "success",
  "warning",
  "danger",
] as const satisfies readonly ConsoleKey[];

/** Everything the UI knows about themes, generated by `racksail theme spec`. */
export interface ThemeSpec {
  themes: Theme[];
  pairs: Pair[];
  derivations: Derivation[];
  meanings: Meaning[];
  /** The contrasts of the console palette, every color on its background. */
  consolePairs: Pair[];
  /** The only tokens that may have an alpha channel. */
  translucentTokens: string[];
  /** The font families the panel serves; any other comes with its files. */
  bundledFonts: string[];
  protected: Record<"light" | "dark" | "highContrastLight" | "highContrastDark", ProtectedPalette>;
  layerCss: Record<string, string>;
}

/** Where a problem is: one of the palettes, the console palette or the type tokens. */
export type ProblemPlace = "light" | "dark" | "console" | "typography";

/** Something wrong with a theme's tokens, as internal/theme reports it. */
export interface ThemeProblem {
  mode: ProblemPlace;
  kind: "contrast" | "meaning" | "color" | "alpha" | "font";
  /** The token with the problem: a color, or sans or mono for a font. */
  foreground: string;
  background?: string;
  ratio?: number;
  minimum?: number;
  /** More about it: what the pair is for, the hue needed, or the font family. */
  purpose?: string;
}
